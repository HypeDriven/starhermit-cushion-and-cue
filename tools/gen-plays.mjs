// Writes the generated play scripts in tests/native/ from tools/plan.mjs's
// keyboard playthroughs (the rules engine the game ships plays them first,
// so every wait and every score the scripts expect is known):
//   journey-stage.play  Play → First Stroke cleared (First Clear unlocked) → Next → Open Table cleared → home progress
//   learn-lessons.play  all six Learn lessons, each performed to "Lesson complete!" (spin set on the spin pad)
//   house-final.play    the House Final challenge: 8-ball against the house champion to the result
// Run after a rules or content change: npm run plays
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { planTable } from './plan.mjs';

const require = createRequire(import.meta.url);
const Content = require('../js/content.js');
const out = new URL('../tests/native/', import.meta.url);

function lessonConfig(l) {
  return { id: 'lesson-' + l.id, name: l.title, version: l.version, kind: 'learn', seed: l.seed, ruleset: l.ruleset, layout: l.layout,
    cueAt: l.cueAt, balls: l.balls, shotLimit: l.shotLimit, blackLast: !!l.blackLast, startInHand: !!l.startInHand,
    par: { shots: l.shotLimit }, mechanics: { undo: true, hint: true } };
}
const header = (lines) => ['# Generated by tools/gen-plays.mjs (npm run plays): do not edit by hand.', ...lines.map((l) => `# ${l}`)];
const start = (shots) => ['frames 10', 'click Start', 'frames 5', `until 120 ${shots}`];

// ---- Journey: the first two stages through the visible flow
{
  const j1 = planTable(Content.JOURNEY[0]), j2 = planTable(Content.JOURNEY[1]);
  if (!j1.result.youWon || !j2.result.youWon) throw new Error('journey plan lost');
  const lines = [
    ...header(['Play opens journey stage 1 (First Stroke); hinted shots clear it; the results card shows', 'its total and the First Clear achievement; Next opens stage 2, which is cleared too.']),
    'until 300 Play', 'frames 30', 'click =Play', 'until 60 First Stroke',
    ...start(`Shots left ${Content.JOURNEY[0].shotLimit}`), ...j1.lines,
    'until 300 Table clear!', 'frames 30', `expect =${j1.result.score.total}`, 'expect Achievement: First Clear', 'save journey-results',
    'click =Next', 'until 60 Open Table', ...start(`Shots left ${Content.JOURNEY[1].shotLimit}`), ...j2.lines,
    'until 300 Table clear!', 'frames 30', `expect =${j2.result.score.total}`,
    'click =Home', 'until 120 Journey 2/36', 'frames 10', 'save journey-home',
  ];
  writeFileSync(new URL('journey-stage.play', out), lines.join('\n') + '\n');
}

// ---- Learn: every lesson performed
{
  const lines = [...header(['Each Learn lesson from the list, its steps performed (spin set on the spin pad by its arrows)', 'to "Lesson complete!", then home; the list shows them completed.']), 'until 300 Play', 'frames 30'];
  for (const l of Content.LESSONS) {
    const spin = l.steps.some((s) => s.require === 'spin-top') ? { top: 30 } : l.steps.some((s) => s.require === 'spin-side') ? { side: 30 } : null;
    const p = planTable(lessonConfig(l), { lesson: l, spin, quietFirst: l.steps.length > 1 && l.steps[0].require !== 'place' });
    lines.push(`# ${l.title}`, 'click Learn', 'until 60 Six short lessons', 'frames 10', `click ${l.title}`, 'until 60 Expected duration', 'frames 5',
      'click Start', 'frames 5', 'until 120 Step 1/', ...p.lines, 'until 300 Lesson complete!', 'frames 30', 'click =Home', 'until 120 Daily Challenge', 'frames 10');
  }
  lines.push('click Learn', 'until 60 Six short lessons', 'frames 20', 'expect The 8 goes last, Completed', 'save learn-done');
  writeFileSync(new URL('learn-lessons.play', out), lines.join('\n') + '\n');
}

// ---- Challenges: House Final, 8-ball against the champion
{
  const ch = Content.CHALLENGES.find((c) => c.id === 'house-final');
  const p = planTable(ch, { maxShots: 60 });
  const headline = p.result.youWon ? 'You win the match!' : 'The house wins.';
  const lines = [
    ...header(['Challenges → House Final: an 8-ball rack against the house champion (skill 0.85), the player', `taking hinted shots, the house its own seeded shots after its pacing, to "${headline}"`]),
    'until 300 Play', 'frames 30', 'click Challenges', 'until 60 Fixed seeds', 'frames 10', 'click House Final', 'until 60 Expected duration',
    ...start('Shots 0'), ...p.lines, `until 400 ${headline}`, 'frames 30', `expect =${p.result.score.total}`, 'save house-final', 'click =Home', 'until 120 Daily Challenge',
  ];
  writeFileSync(new URL('house-final.play', out), lines.join('\n') + '\n');
}
console.log('wrote tests/native/journey-stage.play, learn-lessons.play, house-final.play');
